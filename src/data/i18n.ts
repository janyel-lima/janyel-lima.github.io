export function getModeSpecificMessage(
  key: string,
  lang: Locale,
  realm: ThemeRealm = 'core'
): any {
  const keys = String(key ?? '').split('.');
  if (realm === 'void') {
    let overrideVal: any = traditionalI18nOverrides?.[lang];
    for (const k of keys) {
      if (overrideVal == null) break;
      overrideVal = overrideVal[k];
    }
    if (overrideVal !== undefined) {
      return overrideVal;
    }
  }

  let val: any = i18nMessages?.[lang];
  for (const k of keys) {
    if (val == null) break;
    val = val[k];
  }
  return val;
}
